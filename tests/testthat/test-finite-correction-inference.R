# Over-identified GMMEstimator carries the same t-distribution inference -------

test_that("finite_correction GMM fit reproduces Python theta and variance (over-identified)", {
  ref <- load_fixture("gmm_overid_finite_correction")
  g <- fit_gmm_overid_finite_correction()

  expect_equal(unname(g@theta), ref$theta, tolerance = 1e-6)
  expect_equal(unname(g@variance), as.matrix(ref$variance), tolerance = 1e-6)
  expect_equal(g@n_obs, ref$n_obs)
  # n_params is the number of parameters (two), not the number of moment
  # conditions (three), which sets the t degrees of freedom below.
  expect_equal(g@n_params, ref$n_params)
})

test_that("confidence_intervals() use the t-distribution under finite_correction (GMM over-identified)", {
  ref <- load_fixture("gmm_overid_finite_correction")
  g <- fit_gmm_overid_finite_correction()

  ci <- confidence_intervals(g, alpha = ref$alpha)
  expect_equal(unname(ci[, "lower"]), ref$ci_lower, tolerance = 1e-6)
  expect_equal(unname(ci[, "upper"]), ref$ci_upper, tolerance = 1e-6)
})

test_that("p_values() use the t-distribution under finite_correction (GMM over-identified)", {
  ref <- load_fixture("gmm_overid_finite_correction")
  g <- fit_gmm_overid_finite_correction()

  # Both fixture P-values sit in the interior of (0, 1) (0.031 and 0.143), so
  # the comparison is above the absolute tolerance floor of all.equal.
  p <- p_values(g, null = ref$null)
  expect_equal(unname(p), ref$p_values, tolerance = 1e-6)
})

test_that("GMM t-distribution CIs are wider than the normal-approximation CIs (over-identified)", {
  ref <- load_fixture("gmm_overid_finite_correction")
  g <- fit_gmm_overid_finite_correction()

  ci <- confidence_intervals(g, alpha = ref$alpha)
  se <- sqrt(diag(g@variance))
  z_lower <- g@theta - qnorm(1 - ref$alpha / 2) * se
  z_upper <- g@theta + qnorm(1 - ref$alpha / 2) * se

  # A method that silently used the normal distribution would produce these
  # narrower bounds. The heavier t tails must strictly widen every interval.
  expect_true(all(ci[, "lower"] < z_lower))
  expect_true(all(ci[, "upper"] > z_upper))
})

test_that("GMM t-distribution P-values differ from the normal-approximation P-values (over-identified)", {
  ref <- load_fixture("gmm_overid_finite_correction")
  g <- fit_gmm_overid_finite_correction()

  p_t <- p_values(g, null = ref$null)
  z <- z_scores(g, null = ref$null)
  p_normal <- 2 * pnorm(-abs(z))

  # The t reference gives larger tail probabilities than the normal, so a
  # normal fallback would fail this comparison.
  expect_true(all(p_t > p_normal))
  expect_false(isTRUE(all.equal(
    unname(p_t),
    unname(p_normal),
    tolerance = 1e-6
  )))
})

test_that("GMM t degrees of freedom are n_obs minus n_params, not n_obs minus moments", {
  ref <- load_fixture("gmm_overid_finite_correction")
  g <- fit_gmm_overid_finite_correction()

  ci <- confidence_intervals(g, alpha = ref$alpha)
  se <- sqrt(diag(g@variance))
  # Recover the critical value the fit used from the interval half-width.
  cv <- unname((ci[, "upper"] - g@theta) / se)

  # df uses the two parameters (n - 2 = 18), not the three moment conditions
  # (n - 3 = 17). The two references are numerically distinct.
  expect_equal(
    cv,
    rep(qt(1 - ref$alpha / 2, df = ref$n_obs - ref$n_params), 2),
    tolerance = 1e-8
  )
  cv_moments <- qt(1 - ref$alpha / 2, df = ref$n_obs - 3)
  expect_false(isTRUE(all.equal(cv[1], cv_moments, tolerance = 1e-6)))
})
